/* Big Red One port: the program's entry point.
 *
 * Loads the game's own default.xbe (read as data: its sections are mapped where the Xbox had them, and the
 * recompiled code runs in their place), brings up xboxrecomp's kernel replacement, and calls the game's entry
 * point. Graphics and sound are not emulated: in phase 1 the game's graphics library (NGL) and every Direct3D and
 * DirectSound call from outside it are stand-ins that log and return (stand_ins.c, generated from
 * bro/config/stand_in_functions.tsv).
 *
 * Usage: bro GAME_DIR [SAVE_DIR]
 *   GAME_DIR: the folder holding the game's files from the disc (default.xbe and its data).
 *   SAVE_DIR: where saves go (default: xboxrecomp's choice).
 * Environment: BRO_NGL_LOG=0/1/2 (see src/ngl/ngl_log.h), BRO_FAULT_REPORT / BRO_WRITE_GUARD / BRO_GUARD_MIRRORS (see
 * src/debug/bro_debug.c), and xboxrecomp's own RECOMP_* switches. RECOMP_USB=1 turns
 * on xboxrecomp's USB host controller model, which the game's own XInput code drives to find its gamepads
 * (RECOMP_PAD_SCRIPT / RECOMP_PAD_PRESS then press buttons on a pad nobody holds).
 * Settings: bro.toml next to the program or the folder above it, or the file BRO_SETTINGS names (every setting, its
 * default and its BRO_* variable: bro/config/bro.toml). */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "kernel.h"
#include "xbox_memory_layout.h"
#include "recomp_types.h"
#include "usb/ohci.h"
#include "bro_debug.h"
#include "bro_settings.h"

extern void xbe_entry_point(void);      /* the game's entry point, generated by the recompiler */

static void *read_file(const char *path, size_t *size)
{
    FILE *f = fopen(path, "rb");
    void *data = NULL;
    long n;

    if (!f)
        return NULL;
    if (fseek(f, 0, SEEK_END) == 0 && (n = ftell(f)) > 0 && fseek(f, 0, SEEK_SET) == 0) {
        data = malloc((size_t)n);
        if (data && fread(data, 1, (size_t)n, f) != (size_t)n) {
            free(data);
            data = NULL;
        }
        *size = (size_t)n;
    }
    fclose(f);
    return data;
}

int main(int argc, char **argv)
{
    const char *game_dir, *save_dir;
    char xbe_path[4096];
    size_t xbe_size = 0;
    void *xbe;

    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);
    if (argc < 2) {
        fprintf(stderr, "usage: %s GAME_DIR [SAVE_DIR]\n  GAME_DIR holds the game's files (default.xbe and its data).\n",
                argv[0]);
        return 2;
    }
    game_dir = argv[1];
    save_dir = argc > 2 ? argv[2] : NULL;
    bro_settings_load();        /* bro.toml (src/settings/bro_settings.c), before anything reads a setting */

    snprintf(xbe_path, sizeof xbe_path, "%s/default.xbe", game_dir);
    xbe = read_file(xbe_path, &xbe_size);
    if (!xbe) {
        fprintf(stderr, "Cannot read %s\n", xbe_path);
        return 1;
    }
    printf("[bro] %s: %zu bytes\n", xbe_path, xbe_size);

    if (!xbox_MemoryLayoutInit(xbe, xbe_size)) {
        fprintf(stderr, "[bro] could not map the Xbox address space (the low 64 MB must be free)\n");
        free(xbe);
        return 1;
    }
    g_xbox_mem_offset = xbox_GetMemoryOffset();

    xbox_kernel_init();
    xbox_path_init(game_dir, save_dir);
    xbox_kernel_bridge_init();
    /* Run a file read's completion routine at the game's next alertable wait, as the Xbox does, not inside the
     * read call. The game's file device (FileDevice_IssueIo) marks itself "read pending" only after ReadFileEx
     * returns, and its completion routine (FileDevice_OnIoComplete) ignores a completion that arrives before that.
     * Delivered inline, the first read's completion was dropped and the loading screen waited for it forever. */
    xbox_SetDeferredIoApc(1);
    xbox_OhciInit();            /* does nothing unless RECOMP_USB is set */
    bro_debug_init();           /* crash reports; BRO_WRITE_GUARD and BRO_GUARD_MIRRORS (src/debug/bro_debug.c) */
    g_esp = XBOX_STACK_TOP;

    if (!recomp_dispatch_init())
        fprintf(stderr, "[bro] flat dispatch table unavailable; indirect calls use the binary search\n");
    xbox_WatchdogStart();       /* does nothing unless RECOMP_WATCHDOG_SECS is set */

    printf("[bro] starting the game\n");
    xbe_entry_point();
    printf("[bro] the game returned\n");

    xbox_kernel_shutdown();
    xbox_MemoryLayoutShutdown();
    free(xbe);
    return 0;
}
