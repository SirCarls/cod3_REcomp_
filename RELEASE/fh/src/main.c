/* [acct2-bro] Call of Duty: Finest Hour port: the program's entry point.
 *
 * Loads the game's own default.xbe (read as data: its sections are mapped where the Xbox had them, and the recompiled
 * code runs in their place), brings up xboxrecomp's kernel replacement, and calls the game's entry point. Graphics
 * and sound are not emulated: in phase 1 every function of the game's Direct3D and DirectSound is a stand-in that
 * logs and returns (fh_stand_ins.c, generated from fh/config/stand_in_functions.tsv), or a native answer (fh_d3d.c).
 * Nothing is drawn by a GPU yet; only what the game draws by the CPU (its Bink movie frames) reaches a picture.
 * [waw-decomp] 2026-11-09, phase 2: that picture is shown in a window at each Swap (src/fh_present.c, which lists its
 * FH_* settings), and the device's state calls are kept for the native draws (src/fh_d3d_state.c, FH_DRAW_LOG).
 *
 * Usage: fh GAME_DIR [SAVE_DIR]
 *   GAME_DIR: the folder holding the game's files from the disc (default.xbe and its data).
 *   SAVE_DIR: where saves go (default: xboxrecomp's choice).
 * Environment: FH_LOG=0/1/2 (see src/fh_log.h), FH_SKIP_FILMS=1, FH_ASYNC_IO=0 and FH_LANGUAGE (below),
 * FH_FAULT_REPORT=0, FH_WRITE_GUARD and FH_WHERE (src/fh_debug.c), FH_RELAUNCH=0 (src/fh_relaunch.c) and
 * xboxrecomp's own RECOMP_* switches
 * (RECOMP_USB=1 turns on its USB host controller model, which the game's own XInput code drives to find its gamepads;
 * on Linux x86-64 that model is not available yet). */
