/* FH_SKIP_FILMS=1: every Bink movie (the start-up logos, the intro, the front end's attract loop) stops as soon as it
 * starts, for tests. The game's movie loop (0x000B1BA0 in the Europe v3 default.xbe) clears a stop flag at 0x003B595C
 * when a movie starts and leaves the loop when the flag is set; the game's own skip code (at 0x0012C1B8) sets it, and
 * nothing else reads or writes it (2026-11-08, from the game's code). This holds the flag at 1 with xboxrecomp's
 * RECOMP_POKE, which xboxrecomp reads at start-up, before the game runs. [acct2-fh] 11-15: added once; a level change
 * starts the port again with this environment (src/fh_relaunch.c), where it is there already. */
#define FH_FILM_STOP_FLAG "0x3B595C:1"
#ifdef _WIN32
#define fh_setenv(name, value) _putenv_s(name, value)
#else
#define fh_setenv(name, value) setenv(name, value, 1)
#endif

static void skip_films_if_asked(void)
{
    const char *skip = getenv("FH_SKIP_FILMS");
    const char *poke = getenv("RECOMP_POKE");
    char both[256];

    if (!skip || !skip[0] || strcmp(skip, "0") == 0)
        return;
    if (poke && strstr(poke, FH_FILM_STOP_FLAG)) {
        /* a restart at a level change: there already */
    } else if (poke && poke[0]) {
        snprintf(both, sizeof both, "%s,%s", poke, FH_FILM_STOP_FLAG);
        fh_setenv("RECOMP_POKE", both);
    } else {
        fh_setenv("RECOMP_POKE", FH_FILM_STOP_FLAG);
    }
    printf("[fh] FH_SKIP_FILMS: movies stop as soon as they start\n");
}

/* [acct2-fh] 2026-11-13: a read of a file opened for asynchronous I/O answers "pending", as on the Xbox.
 * xboxrecomp does so only when RECOMP_ASYNC_IO is set (src/kernel/kernel_bridge.c, NtReadFile); without it every read
 * says it finished at once. Finest Hour's stream code (0x00156790 in the Europe v3 default.xbe) takes its stream lock
 * (a semaphore of count 1, 0x003EF484) and, still holding it, reads through RenderWare's file system (0x001569C6 ->
 * 0x00173C80 -> 0x001743E0). A read that finishes at once has its completion callback run in line (0x00174180), and
 * that callback is 0x00156790 again, which waits for the lock its own thread holds: a level's load stopped there for
 * good (dev/agents/acct2-fh/TEST-RUNS.md, boot14). On the console the read is pending and the callback comes later,
 * at an alertable wait, after the lock is let go. On by default; FH_ASYNC_IO=0 turns it off, for comparison. */
static void async_io_unless_asked_not(void)
{
    const char *v = getenv("FH_ASYNC_IO");

    if (v && strcmp(v, "0") == 0) {
        printf("[fh] FH_ASYNC_IO=0: reads of asynchronous files finish at once (levels can stop loading)\n");
        return;
    }
    if (!getenv("RECOMP_ASYNC_IO"))
        fh_setenv("RECOMP_ASYNC_IO", "1");
}

/* [waw-decomp/fh3] 2026-11-23: one guest thread at a time, as on the console's one CPU (fh/README.md: "Run with
 * RECOMP_GUEST_LOCK=1"). The game's loading thread and its main thread change RenderWare's lists (frames, memory
 * blocks, worlds) with no lock of their own: on the Xbox's single core they took turns. The setup tool's play.sh and
 * play.bat set it; fh.exe or fh started any other way (a shortcut, a file manager, a debugger) ran without it and could
 * crash anywhere in play. Now it is on unless RECOMP_GUEST_LOCK is set already (RECOMP_GUEST_LOCK=0 still turns it
 * off, for comparison). */
static void guest_lock_unless_asked_not(void)
{
    if (!getenv("RECOMP_GUEST_LOCK"))
        fh_setenv("RECOMP_GUEST_LOCK", "1");
}

/* [acct2-fh] 2026-11-14: the console's language, from fh.toml's game.language (FH_LANGUAGE). Finest Hour asks the
 * console for it once, at its start (XGetLanguage, 0x001320BE, called only from 0x000A4F70), and sets its own language
 * from the answer (0x00129310): English, French, Italian or Spanish on this disc, English for any other. The game's
 * files follow it (its films from SHELL\MOVIES\<LANGUAGE>\ where the disc has them; text and voices as it picks them).
 * xboxrecomp's kernel answers what xbox_kernel_set_language was given (fh/patches/xboxrecomp_console_language.py),
 * so it is set here, before the game starts. A number 1-9 is the console's own value (1 English, 2 Japanese, 3 German,
 * 4 French, 5 Spanish, 6 Italian, 7 Korean, 8 Chinese, 9 Portuguese). */
static void console_language_from_settings(void)
{
    static const struct { const char *name; ULONG value; } names[] = {
        {"english", 1}, {"japanese", 2}, {"german", 3}, {"french", 4}, {"spanish", 5}, {"italian", 6},
        {"korean", 7}, {"chinese", 8}, {"portuguese", 9},
    };
    const char *text = fh_setting_text("game.language", "FH_LANGUAGE");
    char word[16];
    size_t i;
    ULONG value = 0;

    if (!text || !text[0])
        return;                 /* English, as xboxrecomp answers by itself */
    for (i = 0; i + 1 < sizeof word && text[i]; i++)
        word[i] = (char)((text[i] >= 'A' && text[i] <= 'Z') ? text[i] - 'A' + 'a' : text[i]);
    word[i] = '\0';
    for (i = 0; i < sizeof names / sizeof names[0]; i++)
        if (strcmp(word, names[i].name) == 0)
            value = names[i].value;
    if (!value && word[0] >= '1' && word[0] <= '9' && !word[1])
        value = (ULONG)(word[0] - '0');
    if (!value) {
        fprintf(stderr, "[fh] game.language = \"%s\" isn't a language this port knows; English is used\n", text);
        return;
    }
    xbox_kernel_set_language(value);
    printf("[fh] the console's language: %s (%lu)%s\n", text, (unsigned long)value,
           value == 1 || value == 4 || value == 5 || value == 6 ? "" : "; this disc shows English for it");
}

static void *read_file(const char *path, size_t *size)
{
    FILE *f = fh_fopen(path, "rb");     /* [waw-decomp/fh2] 11-23: a UTF-8 path */
    void *data = NULL;
    long n;

    if (!f)
        return NULL;
    if (fseek(f, 0, SEEK_END) == 0 && (n = ftell(f)) > 0 && fseek(f, 0, SEEK_SET) == 0) {
        data = malloc((size_t)n);
        if (data && fread(data, 1, (size_t)n, f) != (size_t)n) {
            free(data);
            data = NULL;
        }
        *size = (size_t)n;
    }
    fclose(f);
    return data;
}

int main(int argc, char **argv)
{
    const char *game_dir, *save_dir;
    char xbe_path[4096];
    size_t xbe_size = 0;
    void *xbe;

    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);
    fh_host_utf8_args(&argc, &argv);    /* [waw-decomp/fh2] 11-23: on Windows, the arguments as UTF-8 (fh_host.c) */
    fh_console_start();         /* [acct2-fh] 11-14: the log's last lines kept for the console (fh_console.c) */
    if (argc < 2) {
        fprintf(stderr, "usage: %s GAME_DIR [SAVE_DIR]\n  GAME_DIR holds the game's files (default.xbe and its data).\n",
                argv[0]);
        return 2;
    }
    game_dir = argv[1];
    save_dir = argc > 2 ? argv[2] : NULL;
    skip_films_if_asked();
    async_io_unless_asked_not();
    guest_lock_unless_asked_not();

    snprintf(xbe_path, sizeof xbe_path, "%s/default.xbe", game_dir);
    xbe = read_file(xbe_path, &xbe_size);
    if (!xbe) {
        fprintf(stderr, "Cannot read %s\n", xbe_path);
        return 1;
    }
    printf("[fh] %s: %zu bytes\n", xbe_path, xbe_size);

    if (!xbox_MemoryLayoutInit(xbe, xbe_size)) {
        fprintf(stderr, "[fh] could not map the Xbox address space (the low 64 MB must be free)\n");
        free(xbe);
        return 1;
    }
    g_xbox_mem_offset = xbox_GetMemoryOffset();
    fh_relaunch_init(argc, argv);   /* [acct2-fh] 11-15: before the import table is filled (src/fh_relaunch.c) */

    xbox_kernel_init();
    console_language_from_settings();
    xbox_path_init(game_dir, save_dir);
    xbox_kernel_bridge_init();
    fh_relaunch_start();            /* [acct2-fh] 11-15: after a level change, the game's launch data back */
    /* A file read's completion routine runs at the game's next alertable wait, as on the Xbox, not inside the read
     * call (Big Red One's port found a game that drops a completion delivered too early; bro/src/main.c). */
    xbox_SetDeferredIoApc(1);
    xbox_OhciInit();            /* does nothing unless RECOMP_USB is set */
    g_esp = XBOX_STACK_TOP;
    fh_debug_init();            /* [acct2-fh] crash reports; FH_WRITE_GUARD, FH_WHERE (src/fh_debug.c) */

    if (!recomp_dispatch_init())
        fprintf(stderr, "[fh] flat dispatch table unavailable; indirect calls use the binary search\n");
    xbox_WatchdogStart();       /* does nothing unless RECOMP_WATCHDOG_SECS is set */

    printf("[fh] starting the game\n");
    xbe_entry_point();
    printf("[fh] the game returned\n");

    xbox_kernel_shutdown();
    xbox_MemoryLayoutShutdown();
    free(xbe);
    return 0;
}
