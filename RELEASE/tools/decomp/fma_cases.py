#!/usr/bin/env python3
"""Hard test cases for fused multiply-add, with exact answers.

    python3 tools/decomp/fma_cases.py > engine/crates/cod3_game/src/ppc/fma_cases.rs

A fused multiply-add rounds a * b + c once. The usual ways to get it wrong
round twice: through a wider format (the f32 one through f64; the f64 one
through the x87's 80-bit format, as some C libraries do) or not fused at all.
Random inputs almost never hit a case where that shows, so these are built
to: the exact sum lies within a hair of the halfway point between two
neighbors, where the first rounding lands exactly on the halfway point and
the second goes the wrong way. Answers come from exact rational arithmetic
(`fractions.Fraction`), so they don't depend on the machine that runs this.

The Rust tests (`ppc.rs`) check `ppc::fmadds` against the f32 cases and the
platform's `f64::mul_add` (used by the C runtime's `sin`/`cos` port) against
the f64 cases, on every machine `cargo test` runs on.
"""
from __future__ import annotations

import random
import struct
import sys
from fractions import Fraction


class Format:
    def __init__(self, name: str, mantissa_bits: int, min_exponent: int, max_exponent: int, pack: str):
        self.name, self.p, self.emin, self.emax, self.pack = name, mantissa_bits, min_exponent, max_exponent, pack

    def round(self, x: Fraction) -> Fraction:
        """Round to nearest, ties to even, with subnormals; overflow becomes infinity (None)."""
        if x == 0:
            return Fraction(0)
        sign = -1 if x < 0 else 1
        x = abs(x)
        e = x.numerator.bit_length() - x.denominator.bit_length()
        if Fraction(2) ** e > x:
            e -= 1
        e = max(e, self.emin)
        quantum = Fraction(2) ** (e - (self.p - 1))
        q = x / quantum
        n = q.numerator // q.denominator
        rest = q - n
        if rest > Fraction(1, 2) or (rest == Fraction(1, 2) and n % 2 == 1):
            n += 1
        value = n * quantum
        if value >= Fraction(2) ** (self.emax + 1):
            return None
        return sign * value

    def bits(self, x: Fraction) -> int:
        return struct.unpack(">I" if self.pack == "f" else ">Q", struct.pack(">" + self.pack, float(x)))[0]

    def value(self, bits: int) -> Fraction:
        return Fraction(struct.unpack(">" + self.pack, struct.pack(">I" if self.pack == "f" else ">Q", bits))[0])

    def random(self, rng: random.Random, exponent: int) -> Fraction:
        """A random value with `p` significant bits around 2^exponent."""
        mantissa = rng.getrandbits(self.p - 1) | (1 << (self.p - 1))
        return self.round(Fraction(mantissa, 1 << (self.p - 1)) * Fraction(2) ** exponent * rng.choice((1, -1)))


F32 = Format("f32", 24, -126, 127, "f")
F64 = Format("f64", 53, -1022, 1023, "d")
X87 = Format("x87", 64, -16382, 16383, "d")  # only used to round; never packed


def cases(fmt: Format, wider: Format, count: int, seed: int) -> list[tuple[int, int, int, int]]:
    """(a, b, c, a*b+c) bit patterns where rounding through `wider` first gives the wrong answer."""
    rng = random.Random(seed)
    found = []
    while len(found) < count:
        c = fmt.random(rng, rng.randint(-20, 20))
        half_ulp = Fraction(2) ** ((abs(c).numerator.bit_length() - abs(c).denominator.bit_length()) - fmt.p)
        a = fmt.random(rng, rng.randint(-10, 10))
        b = fmt.round(half_ulp / a * rng.choice((1, -1)))
        if b is None or b == 0:
            continue
        exact = a * b + c
        right = fmt.round(exact)
        twice = fmt.round(wider.round(exact))
        if right is not None and right != twice:
            found.append(tuple(fmt.bits(v) for v in (a, b, c, right)))
    return found


def main() -> int:
    out = sys.stdout
    out.write("// Generated by tools/decomp/fma_cases.py; don't edit. Exact answers of\n"
              "// a * b + c rounded once, chosen where rounding twice gives another answer.\n\n")
    for i, (name, fmt, wider, bits) in enumerate((("F32_CASES", F32, F64, 32), ("F64_CASES", F64, X87, 64))):
        width = bits // 4
        if i:
            out.write("\n")
        out.write(f"/// (a, b, c, a * b + c) as bit patterns: {fmt.name}, wrong when rounded through {wider.name} first.\n")
        out.write("#[rustfmt::skip]\n")
        out.write(f"pub const {name}: [(u{bits}, u{bits}, u{bits}, u{bits}); 48] = [\n")
        for case in cases(fmt, wider, 48, seed=bits):
            out.write("    (" + ", ".join(f"0x{v:0{width}X}" for v in case) + "),\n")
        out.write("];\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
