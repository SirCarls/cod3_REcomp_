"""[waw-decomp] 2026-11-16 discmap: write a build's address map, codegen configs and headers.

From map_<build>.tsv (match) and overrides_<build>.tsv (a person's decisions), into OUTDIR:

  address_map.tsv          every address: USA, this build, where the answer came from
  config/...  mp/config/...  the USA codegen configs with each address in the code part of a line
                           carried (campaign: default.toml, names.toml and the level tomls;
                           multiplayer: codmp.toml, codmp_campaign.toml, names_mp.toml). Comments stay
                           as they are, so a diff against the USA file shows nothing but addresses.
                           The names file ends with the hook names: every function the sources name
                           by its USA address (REX_HOOK_RAW(sub_82134B90)) gets that name at its place
                           in this build, so no #define aliases are stacked.
  src/game/...             the USA address table (addresses.h / addresses_mp.h) carried the same way
  build_addresses.h        A(usa): the build's address for a USA address, at compile time; a USA
                           address the build's map lacks stops the compile
  emit_report.txt          what was carried, left out, renamed

acct2-decomp's wip/eu_mp/eu_mp_patch.py did this for the Fr/Es/It program with its own carry rules;
the text substitution here is the same (code part only, comments kept), with the map as its input.
"""
from __future__ import annotations

import re
from pathlib import Path

from common import hex8, write_tsv

HEX = re.compile(r"0x([0-9A-Fa-f]{8})\b")
SUB_NAME = re.compile(r"sub_([0-9A-Fa-f]{8})")


class Problems(list):
    pass


def generated_header(comment: str, build: str, part: str, sha1: str, source: str) -> str:
    lines = [f"GENERATED by tools/discmap (discmap.py emit {build}) from the USA {source}, for build",
             f"{build}: {part}, decrypted SHA-1 {sha1}.",
             f"Every address in the code part of a line is carried by map_{build}.tsv and overrides_{build}.tsv;",
             "comments still describe the USA program. Edit the USA file and run discmap again, not this file."]
    return "".join(f"{comment} {line}\n" for line in lines) + "\n"


def carry_code(code: str, table: dict, known: set, where: str, problems: Problems,
               report: list) -> tuple[str, str]:
    """Carry every address in a piece of code. Returns (new code, state): state is "" when every
    address has an answer, "absent" when one is absent in this build, "unanswered" when one is in
    the map but has no answer (a names-only row that needs a person)."""
    state = ""

    def rep(m):
        nonlocal state
        a = int(m.group(1), 16)
        if a not in table:
            if a in known:
                state = state or "unanswered"
            else:
                problems.append(f"{where}: 0x{a:08X} is not in the build's map (run discmap match again)")
            return m.group(0)
        b, _ = table[a]
        if b is None:
            state = "absent"
            return m.group(0)
        if b != a:
            report.append(f"{where}: 0x{a:08X} -> 0x{b:08X}")
        return f"0x{b:08X}"
    return HEX.sub(rep, code), state


def split_comment(line: str, mark: str) -> tuple[str, str]:
    i = line.find(mark)
    return (line, "") if i < 0 else (line[:i], line[i:])


def carry_toml(text: str, table: dict, known: set, name: str, problems: Problems, report: list,
               names_file: bool = False) -> str:
    """A codegen config with its addresses carried. An entry whose address is absent in this build is
    commented out: a [functions] line, a name, or a whole [[midasm_hook]] block. In a names file, a
    name whose address has no answer (names only, nobody decided) is commented out too."""
    out, block, block_absent = [], [], False

    def flush():
        nonlocal block, block_absent
        if block_absent:
            report.append(f"{name}: a [[midasm_hook]] block left out (an address is absent in this build)")
            out.append("# [discmap] left out: an address of this hook is absent in this build\n")
            out.extend("# " + line if line.strip() else line for line in block)
        else:
            out.extend(block)
        block, block_absent = [], False

    in_hook = False
    for n, line in enumerate(text.splitlines(keepends=True), 1):
        code, comment = split_comment(line, "#")
        stripped = code.strip()
        if stripped.startswith("["):
            flush()
            in_hook = stripped == "[[midasm_hook]]"
        new_code, state = carry_code(code, table, known, f"{name}:{n}", problems, report)
        if state == "unanswered" and not names_file:
            problems.append(f"{name}:{n}: an address here has no answer in the map")
        new_line = new_code + comment
        if in_hook:
            block.append(new_line)
            block_absent |= bool(state)
            continue
        if state:
            if re.match(r"\s*setjmp_address", code):
                problems.append(f"{name}:{n}: setjmp_address cannot be absent")
            why = "absent in this build" if state == "absent" else "not carried (names only; nobody decided)"
            report.append(f"{name}:{n}: left out ({why})")
            new_line = f"# [discmap] {why}: " + line
        out.append(new_line)
    flush()
    return "".join(out)


def carry_header(text: str, table: dict, name: str, report: list) -> str:
    """An address table header (addresses.h / addresses_mp.h): every address in the code part carried;
    an absent one becomes 0, an address the map doesn't have is left as it is and reported."""
    out = []
    for n, line in enumerate(text.splitlines(keepends=True), 1):
        code, comment = split_comment(line, "//")

        def rep(m):
            a = int(m.group(1), 16)
            if a not in table:
                report.append(f"{name}:{n}: 0x{a:08X} not in the map: left as it is")
                return m.group(0)
            b, _ = table[a]
            return "0x00000000" if b is None else f"0x{b:08X}"
        out.append(HEX.sub(rep, code) + comment)
    return "".join(out)


def hook_names(rows, resolver, program: str, table: dict, names_by_addr: dict, functions: set[int], build: str,
               problems: Problems, report: list) -> list[str]:
    """The names file's last section: each function the sources name by its USA address (sub_XXXXXXXX
    in REX_HOOK_RAW / REX_EXTERN, after mp_aliases.h) gets that name at its place in this build. When
    that name is also the default name of another function of this build (the address it has here),
    that function gets a name of its own, so two functions never share a name."""
    lines, assigned = [], dict(names_by_addr)       # build address -> name
    wanted = {}
    for r in rows:
        if r.program != program or r.kind not in ("hook", "orig", "call") or r.addr is None:
            continue
        sym = resolver.symbol(r.symbol, program).removeprefix("__imp__")
        m = SUB_NAME.fullmatch(sym)
        if not m or int(m.group(1), 16) != r.addr or r.addr not in table:
            continue
        b, _ = table[r.addr]
        if b is None or b == r.addr:
            continue
        wanted[b] = sym
    taken = set(assigned.values())
    for b, sym in sorted(wanted.items()):
        if assigned.get(b) not in (None, sym):
            problems.append(f"hook name {sym} at 0x{b:08X}: that address already has the name {assigned[b]}")
            continue
        assigned[b] = sym
        lines.append(f'0x{b:08X} = "{sym}"   # [discmap] the USA name of this function\n')
    taken = set(assigned.values())
    for b, sym in sorted(wanted.items()):
        clash = int(sym[4:], 16)      # this build's own function at that address would default to sym
        if clash in functions and clash not in assigned:
            new = f"sub_{clash:08X}_{build}"
            if new in taken:
                problems.append(f"cannot rename the function at 0x{clash:08X}: {new} is taken")
                continue
            assigned[clash] = new
            taken.add(new)
            lines.append(f'0x{clash:08X} = "{new}"   # [discmap] renamed: its default name is {sym}\'s here\n')
            report.append(f"renamed the build's function at 0x{clash:08X} to {new} ({sym} is another function here)")
    if not lines:
        return []
    return ["\n", "# " + "-" * 75 + "\n",
            f"# [discmap] hook names for build {build}: functions the sources name by their USA address\n",
            "# " + "-" * 75 + "\n"] + lines


def build_addresses_h(build: str, part: str, sha1: str, table: dict) -> str:
    pairs = sorted((a, b) for a, (b, _) in table.items())
    body = "".join(f"    {{0x{a:08X}u, 0x{(b or 0):08X}u}},{'  // absent in this build' if b is None else ''}\n"
                   for a, b in pairs)
    return f"""// GENERATED by tools/discmap (discmap.py emit {build}): the addresses of build {build}
// ({part}, decrypted SHA-1 {sha1}), by their USA address. Do not edit: run discmap again.
//
// A(usa) is this build's address for the USA address usa, worked out while compiling. A USA address
// this build's map doesn't have stops the compile ("AddressMissingFromThisBuild ... not a constant
// expression"): add it to the map (discmap match / the overrides file), never a raw address.
// A(0) is 0, and an address a person marked absent in this build is 0 too: code that may meet one
// checks for 0 and switches its feature off.
#pragma once

#include <cstddef>
#include <cstdint>

namespace cod3_build {{

inline constexpr char kBuildId[] = "{build}";

struct AddressPair {{
    std::uint32_t usa;
    std::uint32_t here;
}};

// Sorted by the USA address.
inline constexpr AddressPair kAddresses[] = {{
{body}}};

// Declared, never defined, and not constexpr: reaching it while compiling is the error message.
std::uint32_t AddressMissingFromThisBuild(std::uint32_t usa);

consteval std::uint32_t Lookup(std::uint32_t usa) {{
    if (usa == 0) {{
        return 0;
    }}
    std::size_t low = 0;
    std::size_t high = sizeof(kAddresses) / sizeof(kAddresses[0]);
    while (low < high) {{
        const std::size_t middle = (low + high) / 2;
        if (kAddresses[middle].usa < usa) {{
            low = middle + 1;
        }} else {{
            high = middle;
        }}
    }}
    if (low < sizeof(kAddresses) / sizeof(kAddresses[0]) && kAddresses[low].usa == usa) {{
        return kAddresses[low].here;
    }}
    return AddressMissingFromThisBuild(usa);
}}

}}  // namespace cod3_build

#define A(usa) (::cod3_build::Lookup(usa))
"""


def map_table_rows(map_rows: list[dict], table_by_key: dict) -> list[list]:
    out = []
    for r in map_rows:
        key = (r["program"], int(r["usa_addr"], 16))
        b, source = table_by_key.get(key, (None, "left out (no decision; names only)"))
        if key in table_by_key and b is None:
            source += " (absent)"
        out.append([r["program"], r["usa_addr"], hex8(b), r["status"], source, r["group"], r["kinds"], r["symbols"]])
    return out


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as w:
        w.write(text)


def write_map(path: Path, map_rows: list[dict], table_by_key: dict, meta: dict) -> None:
    write_tsv(path, ["program", "usa_addr", "build_addr", "status", "source", "group", "kinds", "symbols"],
              map_table_rows(map_rows, table_by_key), meta)
