#!/usr/bin/env python3
"""fh_stubs.py - Call of Duty: Finest Hour's phase 1 stand-ins in C, from fh/config/stand_in_functions.tsv.

Finest Hour's Direct3D (the XDK's D3D8 library, in the XBE section D3D) and DirectSound (section DSOUND) are
replaced in phase 1 of the port by stand-ins that log their call and return, so the recompiled game runs with no
GPU and no sound chip emulated (fh/README.md). The table has one row per function: tools/bro_decomp/ngl_stubs.py's
form (address, name, group, stack_bytes, register_args, returns, stand_in_return, params, size, problems), where
stack_bytes is what the function's own "ret N" removes and register_args the registers it reads as arguments, both
read from its instructions. stand_in_return is what the stand-in hands back: zero, one, block, scratch, a number, or a
C call into the port's native part (fh/src/fh_d3d.c) for a function the game can't go on without. Each stand-in reads its arguments the way the recompiled code passes them (return
address at [esp], arguments from [esp+4]), logs them (fh/src/fh_log.c), sets eax and pops the stack as the
original's "ret N" does.

[acct2-bro] 2026-11-08. Usage (the build's step, fh/CMakeLists.txt):
    fh_stubs.py --from-table TABLE_TSV OUT_C
Also writes fh_stand_ins_ids.h next to OUT_C (one id per stand-in, for fh_log_call). Python's standard library only.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "bro_decomp"))
from ngl_stubs import c_name, out_pointer_arg, read_tsv  # noqa: E402

ARG_REGS = ("eax", "ecx", "edx")
MAX_ARGS_LOGGED = 6
# A "ret N" bigger than this is not a real function's: the table's tool read data in the section as code. Such a row's
# stand-in pops only the return address and says so.
MAX_STACK_BYTES = 64

HEADER = """/* Generated by tools/fh_decomp/fh_stubs.py from fh/config/stand_in_functions.tsv. Do not edit by hand.
 *
 * Finest Hour's phase 1 stand-ins: every function of the game's Direct3D (XBE section D3D) and DirectSound (section
 * DSOUND). Each logs its call (fh/src/fh_log.c) and returns, so the recompiled game runs with no GPU and no sound chip
 * emulated. Arguments are read the way the recompiled code passes them (return address at [esp], arguments from
 * [esp+4]); each pops the stack as the original's "ret N" does. */
#include <stdint.h>
#include "recomp_types.h"
#include "fh_log.h"
#include "fh_d3d.h"
"""


def stack_bytes(row):
    """The bytes the original's ret removes, or None when the table has no usable value."""
    v = row["stack_bytes"].strip()
    if not v.isdigit():
        return None
    n = int(v)
    return n if n % 4 == 0 and n <= MAX_STACK_BYTES else None


def write_c(rows, path):
    out = [HEADER]
    for r in rows:
        name, addr = r["name"], int(r["address"], 16)
        n = c_name(name)
        ident = f"FH_{n.upper()}"
        popped = stack_bytes(r)
        regs = [x for x in r["register_args"].split(",") if x in ARG_REGS]
        args = [f"g_{x}" for x in regs] + [f"MEM32(g_esp + {4 + 4 * i})" for i in range((popped or 0) // 4)]
        args = args[:MAX_ARGS_LOGGED]
        nargs = len(args)
        args += ["0"] * (MAX_ARGS_LOGGED - len(args))
        note = f"ret {r['stack_bytes'] or '?'}"
        if regs:
            note += f", arguments in {', '.join(regs)}"
        if r.get("problems"):
            note += f"; {r['problems']}"
        note = note.replace("*/", "* /")
        text = name.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f"/* {name.replace('*/', '* /')} 0x{addr:08X} ({r['group']}): {note} */")
        out.append(f"static void fh_stand_in_{n}(void)")
        out.append("{")
        out.append(f"    fh_log_call({ident}, \"{text}\", {nargs}, {', '.join(args)});")
        out_arg = out_pointer_arg(name)
        if out_arg is not None:
            out.append(f"    {{ uint32_t out = MEM32(g_esp + {4 + 4 * out_arg}); "
                       f"if (out) MEM32(out) = fh_stand_in_block({ident}); }}")
        policy = r["stand_in_return"].strip()
        if policy == "one":
            out.append("    g_eax = 1;")
        elif policy == "block":
            out.append(f"    g_eax = fh_stand_in_block({ident});")
        elif policy == "scratch":
            out.append("    g_eax = fh_stand_in_scratch();")
        elif policy.isdigit() or "(" in policy:
            # a number, or a call into the port's native part (src/fh_d3d.c) that does the work the game needs
            out.append(f"    g_eax = {policy};")
        else:
            out.append("    g_eax = 0;")
        if popped is None:
            out.append("    g_esp += 4;     /* ret size unknown: the table's problems column says why */")
        else:
            out.append(f"    g_esp += {4 + popped};     /* ret {popped} */")
        out.append("}")
        # the recompiler leaves every --manual-functions address undefined; its dispatch table names it sub_<address>
        out.append(f"void sub_{addr:08X}(void) {{ fh_stand_in_{n}(); }}")
        out.append("")
    out.append("/* For recomp_lookup_manual(): the stand-in for an address, or NULL. */")
    out.append("recomp_func_t fh_stand_in_for(uint32_t xbox_va)")
    out.append("{")
    out.append("    switch (xbox_va) {")
    for r in rows:
        out.append(f"    case 0x{int(r['address'], 16):08X}u: return fh_stand_in_{c_name(r['name'])};")
    out.append("    default: return 0;")
    out.append("    }")
    out.append("}")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    ids = ["/* Generated by tools/fh_decomp/fh_stubs.py with fh_stand_ins.c. Do not edit by hand. */", "#pragma once",
           "enum fh_stand_in_id {"]
    ids += [f"    FH_{c_name(r['name']).upper()}," for r in rows]
    ids += ["    FH_ID_COUNT", "};"]
    with open(os.path.join(os.path.dirname(os.path.abspath(path)), "fh_stand_ins_ids.h"), "w", encoding="utf-8",
              newline="\n") as f:
        f.write("\n".join(ids) + "\n")


def main(argv):
    if len(argv) != 3 or argv[0] != "--from-table":
        sys.exit("usage: fh_stubs.py --from-table TABLE_TSV OUT_C")
    rows = read_tsv(argv[1])
    seen = set()
    for r in rows:
        n = c_name(r["name"]).upper()
        if n in seen:
            sys.exit(f"fh_stubs: two rows are named {r['name']} (C name {n}); names must be unique")
        seen.add(n)
    write_c(rows, argv[2])
    unknown = sum(1 for r in rows if stack_bytes(r) is None)
    print(f"fh_stubs: {len(rows)} stand-ins written to {argv[2]} ({unknown} with no usable ret size)")


if __name__ == "__main__":
    main(sys.argv[1:])
