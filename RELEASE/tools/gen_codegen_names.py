#!/usr/bin/env python3
"""Writes recomp/config/names.toml: the codegen's [names] table (SDK patch
0011), so the generated C++ and our hooks read `Com_Frame` instead of
`sub_82536DD0`.

    python3 tools/gen_codegen_names.py [--symbols recomp/config/symbols.toml]
                                       [--avoid <file of names to avoid>] [-o names.toml]

Taken from the symbol map (tools/name_functions.py): functions named with
"known" or "high" confidence, by their C identifier (`cname` for Class::method
names). Left out:
- import thunks and register save/restore helpers (the codegen names those);
- names a C/C++ library or the SDK's runtime already uses (`--avoid`: one name
  per line, e.g. from `nm -D --defined-only libc.so.6 librexruntime.so`), and
  C++ keywords; such a function gets a `_guest` suffix (the game's own copy);
- a name given to two addresses (both keep their sub_ name).
Medium-confidence names stay in symbols.toml only.
"""
import argparse
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
RECOMP = HERE.parent / "COD_3_WAW_Setup-tool" / "recomp"

CPP_KEYWORDS = set("""
alignas alignof and and_eq asm auto bitand bitor bool break case catch char char8_t char16_t char32_t
class compl concept const consteval constexpr constinit const_cast continue co_await co_return co_yield
decltype default delete do double dynamic_cast else enum explicit export extern false float for friend
goto if inline int long mutable namespace new noexcept not not_eq nullptr operator or or_eq private
protected public register reinterpret_cast requires return short signed sizeof static static_assert
static_cast struct switch template this thread_local throw true try typedef typeid typename union
unsigned using virtual void volatile wchar_t while xor xor_eq main
""".split())

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def load_symbols(path: Path) -> list:
    try:
        import tomllib  # Python 3.11+
        with open(path, "rb") as f:
            return tomllib.load(f).get("function", [])
    except ModuleNotFoundError:
        pass
    # Minimal reader for the generated file's own layout (older Pythons).
    out, cur = [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line == "[[function]]":
            cur = {}
            out.append(cur)
        elif line.startswith("[["):
            cur = None
        elif cur is not None and " = " in line:
            k, v = line.split(" = ", 1)
            cur[k] = int(v, 16) if v.startswith("0x") else v.strip('"')
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--symbols", type=Path, default=RECOMP / "config" / "symbols.toml")
    ap.add_argument("--avoid", type=Path, action="append", default=[])
    ap.add_argument("-o", "--output", type=Path, default=RECOMP / "config" / "names.toml")
    a = ap.parse_args()

    avoid = set(CPP_KEYWORDS)
    for p in a.avoid:
        avoid.update(n.strip() for n in p.read_text(encoding="utf-8").split() if n.strip())

    chosen = []
    for f in load_symbols(a.symbols):
        if f.get("confidence") not in ("known", "high"):
            continue
        ev = str(f.get("evidence", ""))
        name = str(f.get("cname") or f.get("name") or "")
        if name.startswith("__imp__") or ev.startswith(("import", "register ")) or name.startswith("__"):
            continue
        if not IDENT.match(name) or name.startswith("sub_"):
            continue
        if name in avoid:
            name += "_guest"
        chosen.append((int(f["address"]), name, f.get("confidence")))

    counts = Counter(n for _, n, _ in chosen)
    dupes = {n for n, c in counts.items() if c > 1}
    chosen = sorted((addr, n, conf) for addr, n, conf in chosen if n not in dupes)

    lines = [
        "# Generated by tools/gen_codegen_names.py from symbols.toml: the codegen's",
        "# readable names (SDK patch 0011). Edit the symbol map or the tool, not this file.",
        f"# {len(chosen)} functions; {len(dupes)} names given to more than one address left out.",
        "",
        "[names]",
    ]
    lines += [f'0x{addr:08X} = "{n}"' for addr, n, _ in chosen]
    a.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(chosen)} names -> {a.output} ({len(dupes)} duplicate names left out)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
