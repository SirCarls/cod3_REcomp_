#!/usr/bin/env python3
"""Writes the dvar reference from docs/dvars.tsv:

  COD_3_WAW_Setup-tool/recomp/src/ui/dvar_help.inc   the console's help lines
  docs/DVARS.md                                      the tables between its markers

    python3 tools/gen_dvar_help.py           write both
    python3 tools/gen_dvar_help.py --check   only say whether both are current (exit 1 if not)

docs/dvars.tsv has one row per dvar (a header row first, tab separated):
  name, category, programs (sp, mp or sp,mp), default, flags_campaign,
  flags_multiplayer, description
The flags are the console's letters (S U R I A L C T); the descriptions are
the port's own words (no game text). Rows are kept in name order.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TSV = ROOT / "docs" / "dvars.tsv"
INC = ROOT / "COD_3_WAW_Setup-tool" / "recomp" / "src" / "ui" / "dvar_help.inc"
DOC = ROOT / "docs" / "DVARS.md"
BEGIN = "<!-- dvar tables: written by tools/gen_dvar_help.py from docs/dvars.tsv; edit the .tsv, not these -->"
END = "<!-- end of the dvar tables -->"

# The same keys and titles as dvar_help.cpp's kCategories, in the doc's order.
CATEGORIES = [
    ("view", "View and field of view"),
    ("hud", "HUD and messages"),
    ("xhair", "Crosshair and hints"),
    ("gun", "Weapon view"),
    ("shock", "Shell shock"),
    ("cam", "Third person and vehicle cameras"),
    ("fx", "Effects"),
    ("r", "Renderer"),
    ("move", "Player movement"),
    ("dmg", "Damage, health and pickups"),
    ("ai", "AI (campaign)"),
    ("mp", "Multiplayer"),
    ("input", "Mouse, controller and keys"),
    ("net", "Network and server"),
    ("fs", "Files and language"),
    ("sys", "System and debugging"),
    ("script", "Level script switches"),
]
COLUMNS = ["name", "category", "programs", "default", "flags_campaign", "flags_multiplayer", "description"]
NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_.]{0,63}$")
FLAGS = re.compile(r"^[SURIALCT]*$")


def read_rows():
    lines = TSV.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].split("\t") != COLUMNS:
        sys.exit(f"{TSV}: the first row must be: " + "\t".join(COLUMNS))
    rows, seen, problems = [], set(), []
    keys = {k for k, _ in CATEGORIES}
    for n, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        cells = line.split("\t")
        if len(cells) != len(COLUMNS):
            problems.append(f"line {n}: {len(cells)} cells, not {len(COLUMNS)}")
            continue
        r = dict(zip(COLUMNS, cells))
        where = f"line {n} ({r['name']})"
        if not NAME.match(r["name"]):
            problems.append(f"{where}: not a dvar name")
        if r["name"].lower() in seen:
            problems.append(f"{where}: listed twice")
        seen.add(r["name"].lower())
        if r["category"] not in keys:
            problems.append(f"{where}: unknown category '{r['category']}'")
        if r["programs"] not in ("sp", "mp", "sp,mp"):
            problems.append(f"{where}: programs is sp, mp or sp,mp")
        for col in ("flags_campaign", "flags_multiplayer"):
            if not FLAGS.match(r[col]):
                problems.append(f"{where}: {col} takes the letters S U R I A L C T")
        text = r["description"]
        if not text or len(text) > 240 or not text.isascii() or "\\" in text or not text.endswith((".", ")")):
            problems.append(f"{where}: the description is one ASCII sentence (no backslashes, at most 240 "
                            f"characters, ending with a period)")
        if not r["default"].isascii() or "\\" in r["default"]:
            problems.append(f"{where}: the default is ASCII with no backslash")
        rows.append(r)
    names = [r["name"].lower() for r in rows]
    if names != sorted(names):
        problems.append("the rows are not in name order (case-insensitive)")
    if problems:
        sys.exit(f"{TSV}:\n  " + "\n  ".join(problems))
    return rows


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def make_inc(rows):
    out = ["// Generated by tools/gen_dvar_help.py from docs/dvars.tsv (the port's own words).",
           "// Sorted by name, lower case (ui/dvar_help.cpp binary-searches it). Don't edit.", ""]
    for r in sorted(rows, key=lambda r: r["name"].lower()):
        progs = {"sp": "kCampaign", "mp": "kMultiplayer", "sp,mp": "kCampaign | kMultiplayer"}[r["programs"]]
        out.append(f"{{{c_string(r['name'])}, {c_string(r['category'])}, {progs}, {c_string(r['description'])}}},")
    return "\n".join(out) + "\n"


def md_cell(s):
    return s.replace("|", "\\|") if s else ""


def make_tables(rows):
    out = [BEGIN, ""]
    by_cat = {k: [] for k, _ in CATEGORIES}
    for r in rows:
        by_cat[r["category"]].append(r)
    for key, title in CATEGORIES:
        items = by_cat[key]
        if not items:
            continue
        out += [f"### {title} ({len(items)})", "", "| dvar | default | flags | in | what it does |",
                "|---|---|---|---|---|"]
        for r in items:
            fl = r["flags_campaign"], r["flags_multiplayer"]
            if r["programs"] == "sp,mp" and fl[0] != fl[1]:
                flags = f"{fl[0] or '-'} / {fl[1] or '-'}"
            else:
                flags = fl[0] or fl[1]
            where = {"sp": "SP", "mp": "MP", "sp,mp": "SP MP"}[r["programs"]]
            default = f"`{md_cell(r['default'])}`" if r["default"] else ""
            out.append(f"| `{r['name']}` | {default} | {flags} | {where} | {md_cell(r['description'])} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def make_doc(rows):
    text = DOC.read_text(encoding="utf-8")
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < a:
        sys.exit(f"{DOC}: the markers are missing:\n{BEGIN}\n{END}")
    return text[:a] + make_tables(rows) + text[b + len(END):]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="only check that both files are current")
    a = ap.parse_args()
    rows = read_rows()
    wanted = {INC: make_inc(rows), DOC: make_doc(rows)}
    stale = [p for p, t in wanted.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
    if a.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is not current: run python3 tools/gen_dvar_help.py")
        return 1 if stale else 0
    for p in stale:
        p.write_text(wanted[p], encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    print(f"{len(rows)} dvars")
    return 0


if __name__ == "__main__":
    sys.exit(main())
