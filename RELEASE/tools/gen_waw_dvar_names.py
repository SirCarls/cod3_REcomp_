#!/usr/bin/env python3
"""Writes recomp/src/ui/waw_dvar_names.inc: the World at War (PC) dvars that
Call of Duty 3 has nothing for, so the console can say so instead of
"unknown command" (see recomp/src/ui/waw_dvars.h).

    python3 tools/gen_waw_dvar_names.py <waw_dvars.json> [-o <file.inc>]

The input is a JSON array of objects with at least "name" and "category"
("same", "alias", "host" or "none"), made from World at War dvar dumps and
Call of Duty 3's own dvar list. Only names are written; the aliases and port
settings are the hand-written table in waw_dvars.cpp.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE.parent / "COD_3_WAW_Setup-tool" / "recomp" / "src" / "ui" / "waw_dvar_names.inc"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("json", type=Path)
    ap.add_argument("-o", "--output", type=Path, default=DEFAULT_OUT)
    a = ap.parse_args()

    entries = json.loads(a.json.read_text(encoding="utf-8"))
    names = sorted({e["name"] for e in entries if e.get("category") == "none"}, key=str.lower)
    out = ["// Generated by tools/gen_waw_dvar_names.py from a list of World at War (PC)",
           "// dvars: the ones Call of Duty 3 has nothing for (see waw_dvars.cpp). Names only.",
           "// clang-format off"]
    line = "  "
    for n in names:
        item = f'"{n}", '
        if len(line) + len(item) > 100:
            out.append(line.rstrip())
            line = "  "
        line += item
    out.append(line.rstrip())
    out.append("// clang-format on")
    a.output.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(names)} names -> {a.output}")


if __name__ == "__main__":
    main()
