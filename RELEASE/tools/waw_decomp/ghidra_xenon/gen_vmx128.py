#!/usr/bin/env python3
"""
gen_vmx128.py - write vmx128.sinc: the Xbox 360 CPU's (Xenon) VMX128 vector
instructions for Ghidra's PowerPC language, so Ghidra can disassemble and
decompile Xbox 360 code (stock Ghidra stops at the first VMX128 instruction).

Encodings: the instruction formats and decode keys of Xenia's PowerPC frontend
(xenia-canary, src/xenia/cpu/ppc/ppc_decode_data.h and ppc_opcode_lookup_gen.cc;
BSD license). Written fresh in SLEIGH here; no Xenia code is copied.

Also adds the Xenon additions in the ordinary opcode space (lvlx/lvrx/stvlx/
stvrx and their "l" forms) that Ghidra's AltiVec doesn't have.

Usage: python3 gen_vmx128.py <out dir>   (writes vmx128.sinc and the .slaspec)
"""
import os
import sys

# ---------------------------------------------------------------------------
# Instruction lists: (name, constraint, format, semantics kind)
# Bit numbers below are SLEIGH's (0 = least significant bit).

LOADSTORE = [  # opcode 4, VX128_1: bits 4-10 = key, bits 0-1 = 3
    ("lvsl128", 0b0000000, "lvsl"),
    ("lvsr128", 0b0000100, "lvsr"),
    ("lvewx128", 0b0001000, "lvewx"),
    ("lvx128", 0b0001100, "lvx"),
    ("stvewx128", 0b0011000, "stvewx"),
    ("stvx128", 0b0011100, "stvx"),
    ("lvxl128", 0b0101100, "lvx"),
    ("stvxl128", 0b0111100, "stvx"),
    ("lvlx128", 0b1000000, "lvlx"),
    ("lvrx128", 0b1000100, "lvrx"),
    ("stvlx128", 0b1010000, "stvlx"),
    ("stvrx128", 0b1010100, "stvrx"),
    ("lvlxl128", 0b1100000, "lvlx"),
    ("lvrxl128", 0b1100100, "lvrx"),
    ("stvlxl128", 0b1110000, "stvlx"),
    ("stvrxl128", 0b1110100, "stvrx"),
]

OP5 = [  # opcode 5, VX128: bits 6-9 = key4, bit 4 = k1
    ("vaddfp128", 0b0000, 1, "VA,VB"),
    ("vsubfp128", 0b0001, 1, "VA,VB"),
    ("vmulfp128", 0b0010, 1, "VA,VB"),
    ("vmaddfp128", 0b0011, 1, "VA,VB,VD"),    # vD = vA*vB + vD
    ("vmaddcfp128", 0b0100, 1, "VA,VD,VB"),   # vD = vA*vD + vB
    ("vnmsubfp128", 0b0101, 1, "VA,VB,VD"),
    ("vmsum3fp128", 0b0110, 1, "VA,VB"),
    ("vmsum4fp128", 0b0111, 1, "VA,VB"),
    ("vpkshss128", 0b1000, 0, "VA,VB"),
    ("vand128", 0b1000, 1, "and"),
    ("vpkshus128", 0b1001, 0, "VA,VB"),
    ("vandc128", 0b1001, 1, "andc"),
    ("vpkswss128", 0b1010, 0, "VA,VB"),
    ("vnor128", 0b1010, 1, "nor"),
    ("vpkswus128", 0b1011, 0, "VA,VB"),
    ("vor128", 0b1011, 1, "or"),
    ("vpkuhum128", 0b1100, 0, "VA,VB"),
    ("vxor128", 0b1100, 1, "xor"),
    ("vpkuhus128", 0b1101, 0, "VA,VB"),
    ("vsel128", 0b1101, 1, "VA,VB,VD"),
    ("vpkuwum128", 0b1110, 0, "VA,VB"),
    ("vslo128", 0b1110, 1, "VA,VB"),
    ("vpkuwus128", 0b1111, 0, "VA,VB"),
    ("vsro128", 0b1111, 1, "VA,VB"),
]

OP6_3 = [  # opcode 6, VX128_3: bits 4-10 = key7
    ("vcfpsxws128", 0b0100011, "VB,UIMM"),
    ("vcfpuxws128", 0b0100111, "VB,UIMM"),
    ("vcsxwfp128", 0b0101011, "VB,UIMM"),
    ("vcuxwfp128", 0b0101111, "VB,UIMM"),
    ("vrfim128", 0b0110011, "VB"),
    ("vrfin128", 0b0110111, "VB"),
    ("vrfip128", 0b0111011, "VB"),
    ("vrfiz128", 0b0111111, "VB"),
    ("vrefp128", 0b1100011, "VB"),
    ("vrsqrtefp128", 0b1100111, "VB"),
    ("vexptefp128", 0b1101011, "VB"),
    ("vlogefp128", 0b1101111, "VB"),
    ("vspltw128", 0b1110011, "VB,UIMM"),
    ("vspltisw128", 0b1110111, "SIMM"),
    ("vupkd3d128", 0b1111111, "VB,UIMM"),
]

OP6_CMP = [  # opcode 6, VX128_R: bits 7-9 = key3, bit 4 = 0, bit 6 = Rc
    ("vcmpeqfp128", 0b000),
    ("vcmpgefp128", 0b001),
    ("vcmpgtfp128", 0b010),
    ("vcmpbfp128", 0b011),
    ("vcmpequw128", 0b100),
]

OP6_X = [  # opcode 6, VX128: bits 6-9 = key4, bit 4 = k1
    ("vrlw128", 0b0001, 1),
    ("vslw128", 0b0011, 1),
    ("vsraw128", 0b0101, 1),
    ("vsrw128", 0b0111, 1),
    ("vmaxfp128", 0b1010, 0),
    ("vminfp128", 0b1011, 0),
    ("vmrghw128", 0b1100, 0),
    ("vmrglw128", 0b1101, 0),
    ("vupkhsb128", 0b1110, 0),
    ("vupklsb128", 0b1111, 0),
]

OP31_X = [  # Xenon's unaligned vector loads/stores in the ordinary X form (opcode 31)
    ("lvlx", 519, "lvlx"), ("lvlxl", 775, "lvlx"), ("lvrx", 551, "lvrx"), ("lvrxl", 807, "lvrx"),
    ("stvlx", 647, "stvlx"), ("stvlxl", 903, "stvlx"), ("stvrx", 679, "stvrx"), ("stvrxl", 935, "stvrx"),
]


def reg_name(i):
    return f"vs{32 + i}" if i < 32 else f"vr{i}"


def gen_sinc():
    out = []
    w = out.append
    w("# VMX128 (Xbox 360 Xenon) vector instructions. Generated by gen_vmx128.py; do not edit.")
    w("# Registers v0-v31 are the AltiVec registers (vs32-vs63); v32-v127 are new.")
    w("")
    w("define register offset=0x9000 size=16 [")
    names = [f"vr{i}" for i in range(32, 128)]
    for k in range(0, len(names), 16):
        w("    " + " ".join(names[k:k + 16]))
    w("];")
    w("")
    w("define token vmx128(32)")
    for f in [
        "x_op=(26,31)", "x_vdl=(21,25)", "x_val=(16,20)", "x_vbl=(11,15)", "x_ra=(16,20)", "x_rb=(11,15)",
        "x_uimm=(16,20)", "x_simm=(16,20) signed", "x_b10=(10,10)", "x_b4_10=(4,10)", "x_b6_9=(6,9)",
        "x_b7_9=(7,9)", "x_b8_10=(8,10)", "x_b9_10=(9,10)", "x_b6_8=(6,8)", "x_b6_7=(6,7)", "x_b6=(6,6)",
        "x_b9=(9,9)", "x_b5=(5,5)", "x_b4=(4,4)", "x_b4_5=(4,5)", "x_vdh=(2,3)", "x_vbh=(0,1)",
        "x_b0_1=(0,1)", "x_xo1_10=(1,10)", "x_xo0_10=(0,10)", "x_b0=(0,0)", "x_rd=(21,25)",
    ]:
        w(f"    {f}")
    w(";")
    w("")
    w("attach variables [ x_ra x_rb ] [")
    w("    r0 r1 r2 r3 r4 r5 r6 r7 r8 r9 r10 r11 r12 r13 r14 r15")
    w("    r16 r17 r18 r19 r20 r21 r22 r23 r24 r25 r26 r27 r28 r29 r30 r31 ];")
    w("")
    for op in ["vmx128_lvsl", "vmx128_lvsr", "vmx128_lvewx", "vmx128_stvewx", "vmx128_lvlx", "vmx128_lvrx",
               "vmx128_stvlx", "vmx128_stvrx"] + [f"{n}" for n, *_ in OP5 if not n.startswith(("vand", "vor", "vxor", "vnor"))] + \
              [n for n, *_ in OP6_3] + [n for n, _ in OP6_CMP] + [n for n, *_ in OP6_X] + \
              ["vperm128", "vsldoi128", "vpermwi128", "vpkd3d128", "vrlimi128", "vadduws"]:
        w(f"define pcodeop {op};")
    w("")
    # register operand subtables (128 constructors each)
    for i in range(128):
        w(f'XVD: "v{i}" is x_vdl={i & 31} & x_vdh={i >> 5} {{ export {reg_name(i)}; }}')
    for i in range(128):
        w(f'XVA: "v{i}" is x_val={i & 31} & x_b5={(i >> 5) & 1} & x_b10={i >> 6} {{ export {reg_name(i)}; }}')
    for i in range(128):
        w(f'XVB: "v{i}" is x_vbl={i & 31} & x_vbh={i >> 5} {{ export {reg_name(i)}; }}')
    w("")
    for i in range(32):
        w(f'XV31: "v{i}" is x_rd={i} {{ export vs{32 + i}; }}')
    w("XRA0: x_ra is x_ra { export x_ra; }")
    w("XRA0: 0 is x_ra=0 { export 0:$(REGISTER_SIZE); }")
    w("XRB: x_rb is x_rb { export x_rb; }")
    w("")

    # ---- loads/stores (opcode 4)
    for name, key, kind in LOADSTORE:
        pat = f"x_op=4 & XVD & XRA0 & XRB & x_b4_10={key} & x_b0_1=3"
        ea = "\ttmp:$(REGISTER_SIZE) = XRA0 + XRB;"
        if kind == "lvx":
            body = [ea, "\ttmp = tmp & 0xfffffffffffffff0;", "\tXVD = *[ram]:16 tmp;"]
        elif kind == "stvx":
            body = [ea, "\ttmp = tmp & 0xfffffffffffffff0;", "\t*[ram]:16 tmp = XVD;"]
        elif kind.startswith("st"):
            body = [ea, f"\tvmx128_{kind}(tmp, XVD);"]
        else:
            body = [ea, f"\tXVD = vmx128_{kind}(tmp);"]
        w(f":{name} XVD,XRA0,XRB is {pat}")
        w("{")
        out.extend(body)
        w("}")
    w("")
    # ---- vsldoi128 (opcode 4, bit 4 = 1; VX128_5, SH in bits 6-9)
    w(":vsldoi128 XVD,XVA,XVB,x_b6_9 is x_op=4 & XVD & XVA & XVB & x_b6_9 & x_b4=1")
    w("{ sh:1 = x_b6_9; XVD = vsldoi128(XVA, XVB, sh); }")
    # ---- opcode 5
    w(":vperm128 XVD,XVA,XVB,x_b6_8 is x_op=5 & XVD & XVA & XVB & x_b6_8 & x_b9=0 & x_b4=0")
    w("{ c:1 = x_b6_8; XVD = vperm128(XVA, XVB, c); }")
    for name, key4, k1, args in OP5:
        pat = f"x_op=5 & XVD & XVA & XVB & x_b6_9={key4} & x_b4={k1}"
        if args in ("and", "andc", "nor", "or", "xor"):
            expr = {"and": "XVA & XVB", "andc": "XVA & ~XVB", "nor": "~(XVA | XVB)", "or": "XVA | XVB", "xor": "XVA ^ XVB"}[args]
            w(f":{name} XVD,XVA,XVB is {pat}")
            w(f"{{ XVD = {expr}; }}")
        else:
            disp = "XVD,XVA,XVB"
            w(f":{name} {disp} is {pat}")
            w(f"{{ XVD = {name}({args.replace('VA', 'XVA').replace('VB', 'XVB').replace('VD', 'XVD')}); }}")
    w("")
    # ---- opcode 6
    w(":vpermwi128 XVD,XVB,XPERM is x_op=6 & XVD & XVB & x_uimm & x_b6_8 & x_b9_10=1 & x_b4_5=1 [ XPERM = (x_b6_8 << 5) | x_uimm; ]")
    w("{ p:1 = XPERM; XVD = vpermwi128(XVB, p); }")
    w(":vpkd3d128 XVD,XVB,x_uimm,x_b6_7 is x_op=6 & XVD & XVB & x_uimm & x_b6_7 & x_b8_10=6 & x_b4_5=1")
    w("{ t:1 = x_uimm; z:1 = x_b6_7; XVD = vpkd3d128(XVD, XVB, t, z); }")
    w(":vrlimi128 XVD,XVB,x_uimm,x_b6_7 is x_op=6 & XVD & XVB & x_uimm & x_b6_7 & x_b8_10=7 & x_b4_5=1")
    w("{ m:1 = x_uimm; z:1 = x_b6_7; XVD = vrlimi128(XVD, XVB, m, z); }")
    for name, key7, args in OP6_3:
        pat = f"x_op=6 & XVD & x_b4_10={key7}"
        if args == "SIMM":
            w(f":{name} XVD,x_simm is {pat} & x_simm")
            w(f"{{ s:4 = x_simm; XVD = {name}(s); }}")
        elif args == "VB,UIMM":
            w(f":{name} XVD,XVB,x_uimm is {pat} & XVB & x_uimm")
            w(f"{{ u:1 = x_uimm; XVD = {name}(XVB, u); }}")
        else:
            w(f":{name} XVD,XVB is {pat} & XVB")
            w(f"{{ XVD = {name}(XVB); }}")
    for name, key3 in OP6_CMP:
        pat = f"x_op=6 & XVD & XVA & XVB & x_b7_9={key3} & x_b4=0"
        w(f":{name} XVD,XVA,XVB is {pat} & x_b6=0")
        w(f"{{ XVD = {name}(XVA, XVB); }}")
        w(f":{name}. XVD,XVA,XVB is {pat} & x_b6=1")
        w(f"{{ XVD = {name}(XVA, XVB); cr6 = vectorCompareResult(XVD); }}" if False else
          f"{{ XVD = {name}(XVA, XVB); cr6 = 0; }}")
    for name, key4, k1 in OP6_X:
        w(f":{name} XVD,XVA,XVB is x_op=6 & XVD & XVA & XVB & x_b6_9={key4} & x_b4={k1}")
        w(f"{{ XVD = {name}(XVA, XVB); }}")
    w("")
    # ---- AltiVec vadduws: left out of Ghidra's altivec.sinc (it shares its encoding with the
    # embedded SPE evfsadd, which this language doesn't include)
    for i in range(32):
        w(f'XVA31: "v{i}" is x_val={i} {{ export vs{32 + i}; }}')
        w(f'XVB31: "v{i}" is x_vbl={i} {{ export vs{32 + i}; }}')
    w(":vadduws XV31,XVA31,XVB31 is x_op=4 & XV31 & XVA31 & XVB31 & x_xo0_10=640")
    w("{ XV31 = vadduws(XVA31, XVB31); }")
    w("")
    # ---- Xenon X-form loads/stores (opcode 31): vrD in bits 21-25 (AltiVec v0-v31)
    for name, xo, kind in OP31_X:
        w(f":{name} XV31,XRA0,XRB is x_op=31 & XV31 & XRA0 & XRB & x_xo1_10={xo} & x_b0=0")
        if kind.startswith("st"):
            w(f"{{ tmp:$(REGISTER_SIZE) = XRA0 + XRB; vmx128_{kind}(tmp, XV31); }}")
        else:
            w(f"{{ tmp:$(REGISTER_SIZE) = XRA0 + XRB; XV31 = vmx128_{kind}(tmp); }}")
    return "\n".join(out) + "\n"


